--changeset sam:300-cedolino
--comment: Cedolino normalizzato. Competenza: anno + mese 1..14 (13 tredicesima, 14 quattordicesima) oppure,
--comment: per i cedolini successivi alla cessazione (FINE_RAPPORTO), progressivo TFR 1..n senza mese.
--comment: periodo_retribuzione = primo giorno del mese di retribuzione stampato.
--comment: periodo_fine_rapporto valorizzato solo per FINE_RAPPORTO (= periodo_retribuzione) per l'unicita' sul periodo.
CREATE TABLE cedolino (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id          BIGINT                   NOT NULL,
    rapporto_id           BIGINT                   NOT NULL,
    tipo                  VARCHAR(20)              NOT NULL,
    anno                  INTEGER                 NOT NULL,
    mese                  INTEGER,
    progressivo_tfr       INTEGER,
    periodo_retribuzione  DATE                     NOT NULL,
    periodo_fine_rapporto DATE,
    data_elaborazione     DATE,
    lordo                 NUMERIC(15, 5),
    netto                 NUMERIC(15, 5),
    totale_competenze     NUMERIC(15, 5),
    totale_trattenute     NUMERIC(15, 5),
    arrotondamento        NUMERIC(15, 5),
    nome_file             VARCHAR(100)             NOT NULL,
    hash_contenuto        VARCHAR(64)              NOT NULL,
    estratto_json         TEXT                     NOT NULL,
    confidenza            NUMERIC(6, 5),
    campi_non_trovati     VARCHAR(4000),
    modello_estrazione    VARCHAR(100),
    acquisito_il          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cedolino_workspace FOREIGN KEY (workspace_id) REFERENCES workspace (id),
    CONSTRAINT fk_cedolino_rapporto FOREIGN KEY (rapporto_id) REFERENCES rapporto_lavoro (id),
    CONSTRAINT uk_cedolino_mese UNIQUE (rapporto_id, anno, mese),
    CONSTRAINT uk_cedolino_tfr UNIQUE (rapporto_id, progressivo_tfr),
    CONSTRAINT uk_cedolino_periodo_tfr UNIQUE (rapporto_id, periodo_fine_rapporto),
    CONSTRAINT uk_cedolino_hash UNIQUE (workspace_id, hash_contenuto),
    CONSTRAINT uk_cedolino_nome_file UNIQUE (workspace_id, nome_file),
    CONSTRAINT ck_cedolino_tipo CHECK (tipo IN ('ORDINARIA', 'TREDICESIMA', 'QUATTORDICESIMA', 'FINE_RAPPORTO')),
    CONSTRAINT ck_cedolino_mese CHECK (mese IS NULL OR mese BETWEEN 1 AND 14),
    CONSTRAINT ck_cedolino_competenza CHECK (
        (tipo = 'ORDINARIA' AND mese BETWEEN 1 AND 12 AND progressivo_tfr IS NULL AND periodo_fine_rapporto IS NULL)
        OR (tipo = 'TREDICESIMA' AND mese = 13 AND progressivo_tfr IS NULL AND periodo_fine_rapporto IS NULL)
        OR (tipo = 'QUATTORDICESIMA' AND mese = 14 AND progressivo_tfr IS NULL AND periodo_fine_rapporto IS NULL)
        OR (tipo = 'FINE_RAPPORTO' AND mese IS NULL AND progressivo_tfr >= 1 AND periodo_fine_rapporto IS NOT NULL)
    ),
    CONSTRAINT ck_cedolino_confidenza CHECK (confidenza IS NULL OR (confidenza >= 0 AND confidenza <= 1))
);
CREATE INDEX ix_cedolino_rapporto ON cedolino (rapporto_id, periodo_retribuzione);

