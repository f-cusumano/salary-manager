--changeset sam:307-caricamento
--comment: Caricamento di un file PDF (elaborazione asincrona). Stato visibile in UI tramite polling.
CREATE TABLE caricamento (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id          BIGINT                   NOT NULL,
    lotto                 UUID                     NOT NULL,
    nome_file_originale   VARCHAR(255)             NOT NULL,
    dimensione            BIGINT                   NOT NULL,
    hash_contenuto        VARCHAR(64)              NOT NULL,
    stato                 VARCHAR(30)              NOT NULL,
    messaggio             VARCHAR(2000),
    cedolino_id           BIGINT,
    cedolino_esistente_id BIGINT,
    creato_il             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    aggiornato_il         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_caricamento_workspace FOREIGN KEY (workspace_id) REFERENCES workspace (id),
    CONSTRAINT fk_caricamento_cedolino FOREIGN KEY (cedolino_id) REFERENCES cedolino (id) ON DELETE SET NULL,
    CONSTRAINT fk_caricamento_cedolino_esistente FOREIGN KEY (cedolino_esistente_id) REFERENCES cedolino (id) ON DELETE SET NULL,
    CONSTRAINT ck_caricamento_stato CHECK (stato IN (
        'IN_CODA', 'IN_LETTURA', 'ACQUISITO', 'DUPLICATO', 'AGGIUNTIVO_NON_GESTITO', 'ERRORE'))
);
CREATE INDEX ix_caricamento_lotto ON caricamento (workspace_id, lotto);
CREATE INDEX ix_caricamento_creato ON caricamento (workspace_id, creato_il);
CREATE INDEX ix_caricamento_cedolino ON caricamento (cedolino_id);
CREATE INDEX ix_caricamento_cedolino_esistente ON caricamento (cedolino_esistente_id);
