CREATE TABLE segnalazione (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id    BIGINT                   NOT NULL,
    rapporto_id     BIGINT                   NOT NULL,
    cedolino_id     BIGINT,
    codice_regola   VARCHAR(50)              NOT NULL,
    tipo            VARCHAR(40)              NOT NULL,
    gravita         VARCHAR(20)              NOT NULL,
    titolo          VARCHAR(200)             NOT NULL,
    descrizione     VARCHAR(2000)            NOT NULL,
    evidenze        TEXT,
    competenza_anno INTEGER,
    competenza_mese INTEGER,
    creato_il       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_segnalazione_rapporto FOREIGN KEY (rapporto_id) REFERENCES rapporto_lavoro (id) ON DELETE CASCADE,
    CONSTRAINT fk_segnalazione_cedolino FOREIGN KEY (cedolino_id) REFERENCES cedolino (id) ON DELETE CASCADE,
    CONSTRAINT fk_segnalazione_workspace FOREIGN KEY (workspace_id) REFERENCES workspace (id),
    CONSTRAINT ck_segnalazione_gravita CHECK (gravita IN ('INFORMATIVA', 'AVVISO', 'ANOMALIA')),
    CONSTRAINT ck_segnalazione_mese CHECK (competenza_mese IS NULL OR competenza_mese BETWEEN 1 AND 14)
);
CREATE INDEX ix_segnalazione_rapporto ON segnalazione (rapporto_id);
CREATE INDEX ix_segnalazione_cedolino ON segnalazione (cedolino_id);
