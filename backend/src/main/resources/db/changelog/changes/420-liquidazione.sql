CREATE TABLE riepilogo_liquidazione_voce (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT         NOT NULL,
    rapporto_id  BIGINT         NOT NULL,
    ordine       INTEGER        NOT NULL,
    tipo         VARCHAR(30)    NOT NULL,
    quantita     NUMERIC(15, 5),
    unita        VARCHAR(10),
    lordo        NUMERIC(15, 5),
    contributi   NUMERIC(15, 5),
    imposte      NUMERIC(15, 5),
    netto        NUMERIC(15, 5),
    nota         VARCHAR(1000),
    CONSTRAINT fk_liquidazione_voce_rapporto FOREIGN KEY (rapporto_id) REFERENCES rapporto_lavoro (id) ON DELETE CASCADE,
    CONSTRAINT fk_liquidazione_voce_workspace FOREIGN KEY (workspace_id) REFERENCES workspace (id),
    CONSTRAINT uk_liquidazione_voce UNIQUE (rapporto_id, ordine)
);
CREATE INDEX ix_liquidazione_voce_workspace ON riepilogo_liquidazione_voce (workspace_id);
