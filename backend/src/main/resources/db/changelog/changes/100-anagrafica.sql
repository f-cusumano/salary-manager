--changeset sam:100-persona
--comment: Persona (dipendente), riconosciuta per codice fiscale all'interno del workspace
CREATE TABLE persona (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id   BIGINT                   NOT NULL,
    codice_fiscale VARCHAR(16)              NOT NULL,
    nome           VARCHAR(100)             NOT NULL,
    cognome        VARCHAR(100)             NOT NULL,
    data_nascita   DATE,
    creato_il      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    aggiornato_il  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_persona_workspace FOREIGN KEY (workspace_id) REFERENCES workspace (id),
    CONSTRAINT uk_persona_cf UNIQUE (workspace_id, codice_fiscale)
);

--changeset sam:101-azienda
--comment: Azienda (datore di lavoro). Matching: CF/P.IVA, poi posizione INPS, poi ragione sociale normalizzata.
--comment: Indirizzo e codice azienda sono attributi aggiornabili, non chiavi.
CREATE TABLE azienda (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id                 BIGINT                   NOT NULL,
    codice_fiscale               VARCHAR(16),
    partita_iva                  VARCHAR(11),
    posizione_inps               VARCHAR(30),
    ragione_sociale              VARCHAR(200)             NOT NULL,
    ragione_sociale_normalizzata VARCHAR(200)             NOT NULL,
    indirizzo                    VARCHAR(300),
    codice_azienda               VARCHAR(50),
    creato_il                    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    aggiornato_il                TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_azienda_workspace FOREIGN KEY (workspace_id) REFERENCES workspace (id),
    CONSTRAINT uk_azienda_cf UNIQUE (workspace_id, codice_fiscale),
    CONSTRAINT uk_azienda_piva UNIQUE (workspace_id, partita_iva)
);
CREATE INDEX ix_azienda_posizione_inps ON azienda (workspace_id, posizione_inps);
CREATE INDEX ix_azienda_ragione_sociale_norm ON azienda (workspace_id, ragione_sociale_normalizzata);

--changeset sam:102-rapporto-lavoro
--comment: Rapporto di lavoro persona-azienda (uno per coppia). Date stampate sui cedolini prevalgono
--comment: su quelle dedotte (primo/ultimo cedolino). CCNL nullable: "CCNL da indicare".
--comment: riferimento_dati = periodo del cedolino da cui provengono date/qualifica/livello (vince il piu' recente).
CREATE TABLE rapporto_lavoro (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id          BIGINT                   NOT NULL,
    persona_id            BIGINT                   NOT NULL,
    azienda_id            BIGINT                   NOT NULL,
    data_assunzione       DATE,
    data_cessazione       DATE,
    qualifica             VARCHAR(100),
    livello               VARCHAR(50),
    codice_dipendente     VARCHAR(50),
    ccnl_codice           VARCHAR(50),
    ccnl_scelto_da_utente BOOLEAN                  NOT NULL DEFAULT FALSE,
    note                  VARCHAR(4000),
    primo_cedolino        DATE,
    ultimo_cedolino       DATE,
    riferimento_dati      DATE,
    creato_il             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    aggiornato_il         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rapporto_workspace FOREIGN KEY (workspace_id) REFERENCES workspace (id),
    CONSTRAINT fk_rapporto_persona FOREIGN KEY (persona_id) REFERENCES persona (id),
    CONSTRAINT fk_rapporto_azienda FOREIGN KEY (azienda_id) REFERENCES azienda (id),
    CONSTRAINT uk_rapporto_persona_azienda UNIQUE (workspace_id, persona_id, azienda_id),
    CONSTRAINT ck_rapporto_date CHECK (data_cessazione IS NULL OR data_assunzione IS NULL OR data_cessazione >= data_assunzione)
);
CREATE INDEX ix_rapporto_persona ON rapporto_lavoro (persona_id);
CREATE INDEX ix_rapporto_azienda ON rapporto_lavoro (azienda_id);
