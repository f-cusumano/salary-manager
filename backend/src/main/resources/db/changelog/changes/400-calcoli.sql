--changeset sam:400-riepilogo-rapporto
--comment: Riepilogo derivato di un rapporto: ricalcolato da zero (cancella e reinserisce) a ogni evento.
CREATE TABLE riepilogo_rapporto (
    rapporto_id              BIGINT PRIMARY KEY,
    workspace_id             BIGINT                   NOT NULL,
    calcolato_il             TIMESTAMP WITH TIME ZONE NOT NULL,
    -- anzianita'
    anzianita_dal            DATE,
    anzianita_al             DATE,
    anzianita_in_corso       BOOLEAN                  NOT NULL DEFAULT FALSE,
    anzianita_anni           INTEGER,
    anzianita_mesi           INTEGER,
    anzianita_fonte_inizio   VARCHAR(30),
    anzianita_fonte_fine     VARCHAR(30),
    -- scatti
    scatti_attuali           INTEGER,
    scatti_max               INTEGER,
    prossimo_scatto          DATE,
    prossimo_scatto_fonte    VARCHAR(30),
    -- retribuzione
    ral                      NUMERIC(15, 5),
    lordo_mensile            NUMERIC(15, 5),
    mensilita                INTEGER,
    minimo                   NUMERIC(15, 5),
    contingenza              NUMERIC(15, 5),
    superminimo              NUMERIC(15, 5),
    importo_scatti           NUMERIC(15, 5),
    altri_elementi_fissi     NUMERIC(15, 5),
    retribuzione_base        NUMERIC(15, 5),
    ral_stimata              BOOLEAN                  NOT NULL DEFAULT FALSE,
    ral_nota                 VARCHAR(1000),
    ral_cedolino_id          BIGINT,
    buoni_pasto              BOOLEAN                  NOT NULL DEFAULT FALSE,
    -- ratei
    ratei_cedolino_id        BIGINT,
    -- TFR
    tfr_totale               NUMERIC(15, 5),
    tfr_quota_mensile        NUMERIC(15, 5),
    tfr_quota_azienda        NUMERIC(15, 5),
    tfr_quota_fondi          NUMERIC(15, 5),
    tfr_quota_busta          NUMERIC(15, 5),
    tfr_anticipi             NUMERIC(15, 5),
    tfr_stima_netto          NUMERIC(15, 5),
    tfr_aliquota             NUMERIC(15, 5),
    tfr_stimato              BOOLEAN                  NOT NULL DEFAULT FALSE,
    tfr_riferimento          DATE,
    tfr_nota                 VARCHAR(1000),
    CONSTRAINT fk_riepilogo_rapporto FOREIGN KEY (rapporto_id) REFERENCES rapporto_lavoro (id) ON DELETE CASCADE,
    CONSTRAINT fk_riepilogo_workspace FOREIGN KEY (workspace_id) REFERENCES workspace (id),
    CONSTRAINT fk_riepilogo_ral_cedolino FOREIGN KEY (ral_cedolino_id) REFERENCES cedolino (id) ON DELETE SET NULL,
    CONSTRAINT fk_riepilogo_ratei_cedolino FOREIGN KEY (ratei_cedolino_id) REFERENCES cedolino (id) ON DELETE SET NULL
);
CREATE INDEX ix_riepilogo_ral_cedolino ON riepilogo_rapporto (ral_cedolino_id);
CREATE INDEX ix_riepilogo_ratei_cedolino ON riepilogo_rapporto (ratei_cedolino_id);

--changeset sam:401-riepilogo-rateo
--comment: Saldi ratei dell'ultimo cedolino con stima del valore economico se liquidati
CREATE TABLE riepilogo_rateo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id   BIGINT         NOT NULL,
    rapporto_id    BIGINT         NOT NULL,
    tipo           VARCHAR(20)    NOT NULL,
    unita          VARCHAR(10)    NOT NULL,
    saldo          NUMERIC(15, 5) NOT NULL,
    valore_stimato NUMERIC(15, 5),
    CONSTRAINT fk_riepilogo_rateo_rapporto FOREIGN KEY (rapporto_id) REFERENCES rapporto_lavoro (id) ON DELETE CASCADE,
    CONSTRAINT fk_riepilogo_rateo_workspace FOREIGN KEY (workspace_id) REFERENCES workspace (id),
    CONSTRAINT uk_riepilogo_rateo UNIQUE (rapporto_id, tipo, unita)
);

--changeset sam:402-indicatore-mensilita
--comment: Indicatori per cedolino calcolati dal confronto con il cedolino precedente (scatto in busta, aumenti)
CREATE TABLE indicatore_mensilita (
    cedolino_id          BIGINT PRIMARY KEY,
    workspace_id         BIGINT         NOT NULL,
    rapporto_id          BIGINT         NOT NULL,
    scatto_in_busta      BOOLEAN        NOT NULL DEFAULT FALSE,
    aumento_fuori_scatti BOOLEAN        NOT NULL DEFAULT FALSE,
    lordo_contrattuale   NUMERIC(15, 5),
    CONSTRAINT fk_indicatore_cedolino FOREIGN KEY (cedolino_id) REFERENCES cedolino (id) ON DELETE CASCADE,
    CONSTRAINT fk_indicatore_rapporto FOREIGN KEY (rapporto_id) REFERENCES rapporto_lavoro (id) ON DELETE CASCADE,
    CONSTRAINT fk_indicatore_workspace FOREIGN KEY (workspace_id) REFERENCES workspace (id)
);
CREATE INDEX ix_indicatore_rapporto ON indicatore_mensilita (rapporto_id);
